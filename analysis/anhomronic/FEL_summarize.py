"""summarize.py -- turn the per-system analysis outputs into one markdown report."""
import glob
import json
import os
import sys

import numpy as np

OUT = os.path.join('_work', 'analysis')
ORDER = ['Pre-active-MSTN', 'APO-MSTN', 'APO-MSTN-ActRII',
         'Traj-MSTN', 'Traj-MSTN-ActRII', 'Active-MSTN']


def read_csv(path):
    if not os.path.exists(path):
        return []
    with open(path, encoding='utf-8') as f:
        head = f.readline().strip().split(',')
        rows = []
        for line in f:
            vals = line.strip().split(',')
            rows.append({k: (float(v) if k not in ('replica', 'basin', 'proj', 'rep_a', 'rep_b') else v)
                         for k, v in zip(head, vals)})
    return rows


def main():
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    lines = []
    lines.append('# R2-4 cMD convergence analysis: data summary\n')
    lines.append('> Generated by _tools/analyze.py; collective variables were recomputed from the raw trajectories with _tools/extract_cvs.py '
                 '(Angle-1 vertex = midpoint of the two C339 SG atoms).\n')
    lines.append('> All systems, replicas and time windows use **the same binning** (fixed within each system); '
                 'basins were defined by k-means on all replica frames of that system and then frozen.\n')

    lines.append('\n## 1. Per-system overview\n')
    lines.append('| System | Basins | Major-basin population per replica (mean +/- SD) | Inter-replica Bhattacharyya (a1d1) | 1-us cumulative vs full |')
    lines.append('|---|---|---|---|---|')

    detail = []
    for system in ORDER:
        pr = read_csv(os.path.join(OUT, '%s_per_replica.csv' % system))
        ac = read_csv(os.path.join(OUT, '%s_across_replica.csv' % system))
        ov = read_csv(os.path.join(OUT, '%s_overlap.csv' % system))
        cu = read_csv(os.path.join(OUT, '%s_cumulative.csv' % system))
        ba = read_csv(os.path.join(OUT, '%s_basins.csv' % system))
        if not pr:
            continue
        k = len(ba)
        pops = ' '.join('B%d=%.2f±%.2f' % (i, a['pop_mean'], a['pop_sd']) for i, a in enumerate(ac))
        bhat = [o for o in ov if o['proj'] == 'a1d1']
        bstr = ', '.join('%.2f' % o['bhattacharyya'] for o in bhat)
        half = [c for c in cu if c['replica'] == 'main' and abs(c['T'] - 1000) < 1]
        h = half[0]['bhattacharyya_vs_full'] if half else float('nan')
        lines.append('| %s | %d | %s | %s | %.2f |' % (system, k, pops, bstr, h))

        detail.append('\n### %s\n' % system)
        detail.append('Basin centres (k-means, frozen and used for all subsets):\n')
        detail.append('| Basin | Angle-1 | Distance-1 | Distance-2 | Population (all frames) |')
        detail.append('|---|---|---|---|---|')
        for b in ba:
            detail.append('| %s | %.1f | %.2f | %.2f | %.3f |'
                          % (b['basin'], b['angle1'], b['d1'], b['d2'], b['pop_overall']))
        detail.append('\nPer-replica populations (95% block-bootstrap CI), transition counts and correlation times:\n')
        detail.append('| Replica | T (ns) | ACT(Angle-1) ns | ACT(D1) ns | Block length ns | Transitions | '
                      + ' | '.join('B%d' % i for i in range(k)) + ' |')
        detail.append('|---' * (k + 6) + '|')
        for r in pr:
            cells = ' | '.join('%.2f [%.2f, %.2f]' % (r['pop_B%d' % i], r['pop_B%d_lo' % i],
                                                      r['pop_B%d_hi' % i]) for i in range(k))
            detail.append('| %s | %.0f | %.0f | %.0f | %.0f | %d | %s |'
                          % (r['replica'], r['T_ns'], r['act_angle1_ns'], r['act_d1_ns'],
                             r['block_ns'], r['n_transitions'], cells))
        detail.append('\nInter-replica spread:\n')
        detail.append('| Basin | Population mean +/- SD | Range | dG mean +/- SD (kcal/mol) |')
        detail.append('|---|---|---|---|')
        for a in ac:
            detail.append('| %s | %.2f ± %.2f | %.2f–%.2f | %.2f ± %.2f |'
                          % (a['basin'], a['pop_mean'], a['pop_sd'], a['pop_min'],
                             a['pop_max'], a['dG_mean'], a['dG_sd']))

    lines.append('\n## 2. Details per system\n')
    lines += detail

    lines.append('\n## 3. How to read\n')
    lines.append('- **Bhattacharyya**: the closer to 1, the more the free-energy landscapes of two replicas overlap;'
                 ' values above 0.8 indicate two samples of the same landscape, values below 0.5 indicate clearly different sampled regions.')
    lines.append('- **ACT(Angle-1)** is the integrated autocorrelation time of Angle-1; for a 2-us trajectory with ACT around 400 ns,'
                 ' there are only about five independent samples, which is why the bootstrap CI is wide.')
    lines.append('- **Block length** = max(2 x ACT(D1), 50 ns), capped at T/5 to avoid too few blocks for resampling.')
    lines.append('- The CI of a basin population reflects uncertainty **within one trajectory**; the inter-replica SD reflects differences **between replicas**,'
                 ' which is what the reviewer means by statistical foundations.')

    path = os.path.join(OUT, 'R2-4_cMD_summary.md')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print('wrote', path)


if __name__ == '__main__':
    main()
